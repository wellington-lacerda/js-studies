// Comparação 

//  < Maior que
//  < Menor que
//  >= Maior ou igual a
//  <=  Menor ou igual a 

//  == igual a
//  === Estritamente igual a
//  != Diferente de 
//  !== Estritamente diferente de

console.log(50 > 3); // true
console.log(50 < 3); // false
console.log(4 >= 3) // true
console.log(4 >= 4) // true
console.log(4 >= 5) // false 

console.log(2 == 2) // true
console.log(2 != 2) // false 
console.log("2" == 2) // true
console.log("2" === 2) // false 

console.log("Wellington" == "wellington") // false, letra maiúscula n é igual a minuscula 

